#!/bin/bash
# ---------------------------------------------------------------------------
# run_ema.sh — host cert for the saved-copy EMA of the resident baby
#              (research/lr-schedule.md; tests/llm/student_ema_test.c).
#   OFF arm (PKERNEL_STUDENT_EMA unset, 2 ticks): today's writes, byte-identical.
#   ON arm  (PKERNEL_STUDENT_EMA=1, 8 ticks): live unchanged, the lower-held
#           copy is written, every second-half write is the copy.
#   FALSIFIER (-DEMA_FOLD_DISABLE, ON, 8 ticks): must FAIL ([ema-helps] RED).
#   WRITER arm (ON): a higher writer of g_student runs inside the copy's
#           held-out evaluation (-Wl,--wrap=st_eval_loss); its update stays in
#           live and the stale copy is not written ([ema-writer-kept]).
#   FALSIFIER (-DEMA_VIEW_DISABLE: the repointing audit-35 failed): the writer
#           arm must FAIL. FALSIFIER (-DEMA_GEN_DISABLE: no generation check at
#           the save -> the copy evaluated before the writer is written): the
#           writer arm must FAIL (this is what shows the copy was about to win).
# exit 0 = OFF, ON and WRITER PASS and the three falsifiers FAIL.
# ---------------------------------------------------------------------------
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
CC="${CC:-cc}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

SRC="$HERE/student_ema_test.c $ROOT/arch/common/llm/student.c $ROOT/arch/common/llm/cradle.c $ROOT/arch/common/llm/dlb.c"
STUB="$WORK/ema_stub.c"
printf '%s\n' \
  '/* auto-generated by run_ema.sh: link-only stubs (chat / frontier verbs are never driven) */' \
  'int conscience_check(unsigned char site, const void *q) { (void)site; (void)q; return 0; }' \
  'const char *conscience_on_refuse(unsigned char site, int verdict) { (void)site; (void)verdict; return ""; }' \
  'void frontier_self_test(void (*emit)(const char *)) { (void)emit; }' > "$STUB"
SRC="$SRC $STUB"
CFLAGS="-std=c11 -O1 -Wall -Wextra -ffp-contract=off"

LDWRAP="-Wl,--wrap=st_eval_loss"   # the writer arm's hook; a pass-through otherwise

echo "[build] compiling saved-copy EMA cert ..."
"$CC" $CFLAGS $SRC $LDWRAP -lm -o "$WORK/ema" || { echo "[build] FAILED"; exit 1; }
echo "[build] compiling falsifier (-DEMA_FOLD_DISABLE) ..."
"$CC" $CFLAGS -DEMA_FOLD_DISABLE $SRC $LDWRAP -lm -o "$WORK/ema_nofold" || { echo "[build] falsifier FAILED"; exit 1; }
echo "[build] compiling falsifier (-DEMA_VIEW_DISABLE) ..."
"$CC" $CFLAGS -DEMA_VIEW_DISABLE $SRC $LDWRAP -lm -o "$WORK/ema_noview" || { echo "[build] falsifier FAILED"; exit 1; }
echo "[build] compiling falsifier (-DEMA_GEN_DISABLE) ..."
"$CC" $CFLAGS -DEMA_GEN_DISABLE $SRC $LDWRAP -lm -o "$WORK/ema_nogen" || { echo "[build] falsifier FAILED"; exit 1; }

echo ""; echo "=== OFF (PKERNEL_STUDENT_EMA unset; must PASS) ==="
( cd "$ROOT" && env -u PKERNEL_STUDENT_EMA "$WORK/ema" 2 ); OFF_RC=$?
echo ""; echo "=== ON (PKERNEL_STUDENT_EMA=1; must PASS) ==="
( cd "$ROOT" && PKERNEL_STUDENT_EMA=1 "$WORK/ema" 8 ); ON_RC=$?
echo ""; echo "=== falsifier -DEMA_FOLD_DISABLE, ON (must FAIL = RED) ==="
( cd "$ROOT" && PKERNEL_STUDENT_EMA=1 "$WORK/ema_nofold" 8 ); NF_RC=$?
echo ""; echo "=== WRITER (PKERNEL_STUDENT_EMA=1; must PASS) ==="
( cd "$ROOT" && PKERNEL_STUDENT_EMA=1 "$WORK/ema" writer ); WR_RC=$?
echo ""; echo "=== falsifier -DEMA_VIEW_DISABLE, WRITER (must FAIL = RED) ==="
( cd "$ROOT" && PKERNEL_STUDENT_EMA=1 "$WORK/ema_noview" writer ); NV_RC=$?
echo ""; echo "=== falsifier -DEMA_GEN_DISABLE, WRITER (must FAIL = RED) ==="
( cd "$ROOT" && PKERNEL_STUDENT_EMA=1 "$WORK/ema_nogen" writer ); NG_RC=$?

echo ""
if [ "$OFF_RC" -eq 0 ] && [ "$ON_RC" -eq 0 ] && [ "$NF_RC" -ne 0 ] && \
   [ "$WR_RC" -eq 0 ] && [ "$NV_RC" -eq 1 ] && [ "$NG_RC" -eq 1 ]; then
  echo "[result] PASS  saved-copy EMA: off identical, on helps, writer kept, three falsifiers RED"
  exit 0
fi
echo "[result] FAIL  off_rc=$OFF_RC on_rc=$ON_RC falsifier_rc=$NF_RC writer_rc=$WR_RC noview_rc=$NV_RC nogen_rc=$NG_RC (want 0 0 !=0 0 1 1)"
exit 1
